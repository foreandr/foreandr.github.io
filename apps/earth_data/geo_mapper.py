def geojson_has_country(name: str) -> bool:
    """True if `name` is exactly one of the GeoJSON feature names."""
    return name in CANONICAL_GEOJSON_NAMES

def get_normalized_name(raw_label: Optional[str]) -> str:
    """
    Return the best-match GeoJSON feature name for a raw dataset label.

    Matching order:
      1) Exact key match in GEO_NAME_MAP
      2) Simple pattern fixes (', The' -> 'The X')
      3) Normalized-key lookup (case/punct/diacritics insensitive)
      4) Fallback: return cleaned raw label unchanged

    IMPORTANT:
      - If the returned string is NOT in CANONICAL_GEOJSON_NAMES, your
        renderer should treat it as 'no match' (leave country uncolored).
    """
    if not raw_label:
        return 'Unknown'

    clean = raw_label.strip()
    if not clean:
        return 'Unknown'

    # 1) Direct map check (fast path)
    if clean in GEO_NAME_MAP:
        return GEO_NAME_MAP[clean]

    # 2) Pattern matching: Handle 'X, The' and similar
    #    (World Bank often uses 'Bahamas, The', 'Gambia, The', etc.)
    if clean.endswith(', The'):
        base = clean[:-5].strip()
        candidate = f'The {base}'
        if candidate in GEO_NAME_MAP:
            return GEO_NAME_MAP[candidate]
        # try direct canonical if present
        if candidate in CANONICAL_GEOJSON_NAMES:
            return candidate
        # otherwise keep going with normalized lookup
        clean = candidate

    # Some datasets store 'The X' while others store 'X'.
    # We'll try both forms through normalized lookup below.

    # 3) Normalized lookup
    nk = _normalize_key(clean)
    if nk in GEO_NAME_MAP_NORM:
        return GEO_NAME_MAP_NORM[nk]

    # 4) Fallback
    return clean