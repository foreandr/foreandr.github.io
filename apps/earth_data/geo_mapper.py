# ============================================================
# NORMALIZATION HELPERS
# ============================================================
_WS_RE = re.compile(r"\s+")
_PUNCT_RE = re.compile(r"[^a-z0-9]+")

def _strip_accents(s: str) -> str:
    """Remove diacritics/accents (e.g., “Zaïre” -> “Zaire”)."""
    return ''.join(ch for ch in unicodedata.normalize('NFKD', s) if not unicodedata.combining(ch))

def _normalize_key(s: str) -> str:
    """Canonicalize a label for fuzzy dictionary lookup (case/space/punctuation/diacritics-insensitive)."""
    s = s.strip()
    if not s:
        return ''
    # unify apostrophes/quotes
    s = s.replace('’', "'").replace('‘', "'").replace('“', '"').replace('”', '"')
    s = _strip_accents(s)
    s = s.lower()
    s = _PUNCT_RE.sub(' ', s)
    s = _WS_RE.sub(' ', s).strip()
    return s

# Build a normalized lookup map so you can match things like:
#   'Congo, Dem. Rep.' == 'congo dem rep' -> 'Democratic Republic of the Congo'
GEO_NAME_MAP_NORM: dict[str, str] = {}
for _k, _v in GEO_NAME_MAP.items():
    nk = _normalize_key(_k)
    if nk and nk not in GEO_NAME_MAP_NORM:
        GEO_NAME_MAP_NORM[nk] = _v

# Also allow direct matching of canonical names through normalized lookup.
for _name in CANONICAL_GEOJSON_NAMES:
    nk = _normalize_key(_name)
    if nk and nk not in GEO_NAME_MAP_NORM:
        GEO_NAME_MAP_NORM[nk] = _name

